// Package the pinned, self-contained Three.js module for direct file:// launch.
import {readFile,writeFile} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const three=await readFile(new URL('vendor/three.module.js',root),'utf8');
const match=three.match(/export\s*\{([^}]+)\};?\s*$/);
if(!match||/^import\s/m.test(three))throw new Error('Unexpected Three.js module structure');
const entries=match[1].split(',').map(s=>{const [local,alias]=s.trim().split(/\s+as\s+/);return `${alias||local}: ${local}`;});
const game=await readFile(new URL('src/action.js',root),'utf8');
if(!game.startsWith("import * as T from '../vendor/three.module.js';"))throw new Error('Unexpected action entry point');
await writeFile(new URL('src/action.bundle.js',root),`/* Generated by scripts/bundle-action.mjs. Three.js MIT license: vendor/THREE-LICENSE.txt */\n(()=>{\nconst T=(()=>{\n${three.slice(0,match.index)}\nreturn {${entries.join(',')}};\n})();\n${game.replace(/^import[^\n]+\n/,'')}\n})();\n`);
